// Какие справочники включать полностью / сокращённо
const WORK_TYPE_PRIORITY = {
  cosmetic: {
    full: ["отделочные"],
    headers: ["сантехнические", "электромонтажные"],
  },
  capital: {
    full: ["отделочные", "электромонтажные"],
    headers: ["строительные", "сантехнические", "вентиляция"],
  },
  construction: {
    full: ["строительные"],
    headers: ["отделочные", "сантехнические", "электромонтажные", "вентиляция"],
  },
  landscaping: {
    full: ["благоустройство"],
    headers: [],
  },
};

/**
 * Читает файл справочника и возвращает только заголовки разделов.
 */
function extractSectionHeaders(filePath) {
  const text = fs.readFileSync(filePath, "utf-8");
  return text
    .split("\n")
    .filter((l) => l.startsWith("## "))
    .join("\n");
}

/**
 * Формирует блок расценок для системного промпта.
 * @param {string} workType - cosmetic | capital | construction | landscaping
 * @param {string} region - spb | lo | msk | mo
 * @returns {string} текстовый блок для промпта
 */
function buildPriceContext(workType, region) {
  const priority = WORK_TYPE_PRIORITY[workType];
  if (!priority) return "";

  const isMoscow = region === "msk" || region === "mo";
  const isMO = region === "mo";

  let ctx = `\n## СПРАВОЧНИК РАСЦЕНОК НА РАБОТЫ (СПб, март 2026)\n`;
  ctx += `Коэффициент инфляции Кинф = ${K_INF} (март→июль 2026)\n`;

  if (isMoscow) {
    ctx += `Регион: ${isMO ? "Московская область" : "Москва"}\n`;
    ctx += `Применяй поправочный коэффициент Кмск к расценкам на РАБОТЫ (не к материалам).\n`;
    if (isMO) {
      ctx += `Для Московской области Кмск на 5% ниже, чем для Москвы.\n`;
    }
    ctx += `\nДетализированные Кмск (приоритет — ищи вид работы в этой таблице):\n`;
    for (const [work, k] of Object.entries(K_MSK_DETAILED)) {
      ctx += `  ${work}: ${k}\n`;
    }
    ctx += `\nУсреднённые Кмск (если вид работы не найден в детализации):\n`;
    for (const [dir, k] of Object.entries(K_MSK)) {
      if (!dir.includes("_")) ctx += `  ${dir}: ${k}\n`;
    }
    ctx += `\nФормула: Расценка_итог = Расценка_СПб × Кинф × Кмск\n`;
  } else {
    ctx += `Регион: ${region === "spb" ? "Санкт-Петербург" : "Ленинградская область"}\n`;
    ctx += `Формула: Расценка_итог = Расценка_СПб × Кинф\n`;
  }

  ctx += `\nЕсли в справочнике указан диапазон (мин-макс), используй среднее значение.\n`;
  ctx += `Если конкретная работа не найдена в справочнике — используй web_search.\n\n`;

  // Full directories
  const pricesDir = path.join(__dirname, "..", "app", "prices");
  for (const dir of priority.full) {
    const filePath = path.join(pricesDir, `${dir}.txt`);
    if (fs.existsSync(filePath)) {
      const content = fs.readFileSync(filePath, "utf-8");
      ctx += `### РАСЦЕНКИ: ${dir.toUpperCase()} (полный справочник)\n`;
      ctx += `Формат: Код\\tНаименование\\tЕд.\\tЦена(₽)\n`;
      ctx += content + "\n\n";
    }
  }

  // Headers only
  for (const dir of priority.headers) {
    const filePath = path.join(pricesDir, `${dir}.txt`);
    if (fs.existsSync(filePath)) {
      const headers = extractSectionHeaders(filePath);
      ctx += `### РАСЦЕНКИ: ${dir.toUpperCase()} (только разделы — детали через web_search)\n`;
      ctx += headers + "\n\n";
    }
  }

  return ctx;
}

module.exports = { buildPriceContext, K_INF, K_MSK, K_MSK_DETAILED, WORK_TYPE_PRIORITY };
